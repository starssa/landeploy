"""Downloadable tools the server keeps for the LAN: iPXE boot files and an
offline copy of Python for Windows (embeddable zip for the agent + full installer)."""
import json
import os
import re
import threading
import urllib.request
from pathlib import Path

import fetch_bootfiles

PY_FTP = os.environ.get("LANDEPLOY_PYTHON_MIRROR", "https://www.python.org/ftp/python/")
# key -> (stored file name, python.org file pattern)
PYTHON_FILES = {
    "python-embed": ("python-embed-amd64.zip", "python-{v}-embed-amd64.zip"),
    "python-installer": ("python-installer-amd64.exe", "python-{v}-amd64.exe"),
}
UPLOADABLE = {name for name, _ in PYTHON_FILES.values()}


def _exists(url):
    try:
        with urllib.request.urlopen(urllib.request.Request(url, method="HEAD"), timeout=15) as r:
            return r.status == 200
    except Exception:
        return False


def python_versions():
    html = urllib.request.urlopen(PY_FTP, timeout=20).read().decode(errors="replace")
    found = {tuple(map(int, m)) for m in re.findall(r'href="(\d+)\.(\d+)\.(\d+)/"', html)}
    return [".".join(map(str, v)) for v in sorted(found, reverse=True) if v[0] == 3]


def download(url, dest, progress):
    tmp = dest.with_name(dest.name + ".part")
    with urllib.request.urlopen(url, timeout=60) as r, open(tmp, "wb") as f:
        total, done = int(r.headers.get("Content-Length") or 0), 0
        while True:
            chunk = r.read(1 << 20)
            if not chunk:
                break
            f.write(chunk)
            done += len(chunk)
            progress(done, total)
    tmp.replace(dest)


class Tools:
    def __init__(self, tools_dir, bootfiles_dir):
        self.dir, self.boot = Path(tools_dir), Path(bootfiles_dir)
        self.dir.mkdir(parents=True, exist_ok=True)
        self.meta_file = self.dir / "tools.json"
        self.status = {}

    def meta(self):
        try:
            return json.loads(self.meta_file.read_text())
        except Exception:
            return {}

    def set_meta(self, key, value):
        m = self.meta()
        m[key] = value
        self.meta_file.write_text(json.dumps(m))

    def info(self):
        m, out = self.meta(), {}
        for key, (name, _) in PYTHON_FILES.items():
            p = self.dir / name
            out[key] = {"file": name, "present": p.is_file(), "size": p.stat().st_size if p.is_file() else 0,
                        "version": m.get(key, ""), **self.status.get(key, {})}
        missing = fetch_bootfiles.missing_files(self.boot)
        out["bootfiles"] = {"present": not missing, "missing": missing, **self.status.get("bootfiles", {})}
        return out

    def fetch(self, what):
        if what not in ("bootfiles", *PYTHON_FILES):
            raise ValueError("unknown tool")
        if self.status.get(what, {}).get("state") == "running":
            return
        self.status[what] = {"state": "running", "msg": "starting..."}
        threading.Thread(target=self._run, args=(what,), daemon=True).start()

    def _run(self, what):
        st = self.status[what]
        try:
            if what == "bootfiles":
                missing = fetch_bootfiles.fetch(self.boot, log=lambda msg: st.update(msg=msg.strip()))
                if missing:
                    raise RuntimeError("still missing: " + ", ".join(missing) + " (Ubuntu/Debian: sudo apt install ipxe, then click Download again)")
                st.update(state="done", msg="All boot files ready")
                return
            name, pattern = PYTHON_FILES[what]
            st["msg"] = "Looking for the latest Python on python.org..."
            for v in python_versions()[:10]:
                url = f"{PY_FTP}{v}/{pattern.format(v=v)}"
                if _exists(url):
                    break
            else:
                raise RuntimeError("no Windows build found on python.org")
            download(url, self.dir / name,
                     lambda d, t: st.update(msg=f"Python {v}: {d >> 20} / {t >> 20} MB"))
            self.set_meta(what, v)
            st.update(state="done", msg=f"Python {v} ready")
        except Exception as e:
            st.update(state="error", msg=str(e))



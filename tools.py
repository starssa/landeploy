"""Things the server hands out on the LAN: iPXE boot files (downloaded on request) and the
LANDeploy agent as a standalone program for client PCs (bundled with release builds, so
client PCs need neither Python nor Internet access)."""
import threading
from pathlib import Path

import fetch_bootfiles

# target -> file name of the compiled agent (built by the release workflow, see build.py)
AGENTS = {
    "windows-x64": "landeploy-agent-windows-x64.exe",
    "linux-x64": "landeploy-agent-linux-x64",
    "linux-arm64": "landeploy-agent-linux-arm64",
}


class Tools:
    def __init__(self, tools_dir, bootfiles_dir, agent_dirs=()):
        self.dir, self.boot = Path(tools_dir), Path(bootfiles_dir)
        self.dir.mkdir(parents=True, exist_ok=True)
        # bundled agents first, then data/tools (lets you drop in your own builds when running from source)
        self.agent_dirs = [Path(d) for d in agent_dirs] + [self.dir]
        self.status = {}

    def agent_file(self, name):
        if name not in AGENTS.values():
            return None
        return next((d / name for d in self.agent_dirs if (d / name).is_file()), None)

    def info(self):
        agents = {}
        for target, name in AGENTS.items():
            f = self.agent_file(name)
            agents[target] = {"file": name, "present": bool(f), "size": f.stat().st_size if f else 0}
        missing = fetch_bootfiles.missing_files(self.boot)
        return {"agents": agents,
                "bootfiles": {"present": not missing, "missing": missing, **self.status.get("bootfiles", {})}}

    def fetch(self, what):
        if what != "bootfiles":
            raise ValueError("unknown tool")
        if self.status.get(what, {}).get("state") == "running":
            return
        self.status[what] = {"state": "running", "msg": "starting..."}
        threading.Thread(target=self._run, daemon=True).start()

    def _run(self):
        st = self.status["bootfiles"]
        try:
            missing = fetch_bootfiles.fetch(self.boot, log=lambda msg: st.update(msg=msg.strip()))
            if missing:
                raise RuntimeError("still missing: " + ", ".join(missing) +
                                   " (Ubuntu/Debian: sudo apt install ipxe, then click Download again)")
            st.update(state="done", msg="All boot files ready")
        except Exception as e:
            st.update(state="error", msg=str(e))


# ------------------------------------------------------------------ agent setup scripts
def setup_ps1(base, token):
    return f"""# LANDeploy agent setup for Windows - generated by {base}
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
$S = '{base}'; $T = '{token}'; $D = "$env:ProgramData\\LANDeploy-Agent"; $Old = "$env:ProgramData\\LANDeploy"
$admin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
if (-not $admin) {{ Write-Host 'Please run this as Administrator (right-click > Run as administrator).' -ForegroundColor Red; return }}
Write-Host '== LANDeploy agent setup ==' -ForegroundColor Cyan
Stop-ScheduledTask -TaskName LANDeploy -ErrorAction SilentlyContinue
Get-Process landeploy-agent, pythonw -ErrorAction SilentlyContinue | Where-Object {{ $_.Path -like "$D*" -or $_.Path -like "$Old\\python*" }} | Stop-Process -Force
Start-Sleep -Seconds 1
New-Item -ItemType Directory -Force -Path $D | Out-Null
Write-Host 'Downloading the agent from the LANDeploy server...'
try {{ Invoke-WebRequest "$S/agent/bin/{AGENTS['windows-x64']}" -OutFile "$D\\landeploy-agent.exe" -UseBasicParsing }}
catch {{ Write-Host "The server has no Windows agent program: use a LANDeploy release build (github.com/starssa/landeploy/releases)." -ForegroundColor Red; return }}
Remove-Item "$Old\\python", "$Old\\landeploy_agent.py" -Recurse -Force -ErrorAction SilentlyContinue   # old Python-based agent
$action = New-ScheduledTaskAction -Execute "$D\\landeploy-agent.exe" -Argument "--server $S --token $T" -WorkingDirectory $D
$trigger = New-ScheduledTaskTrigger -AtStartup
$principal = New-ScheduledTaskPrincipal -UserId 'SYSTEM' -LogonType ServiceAccount -RunLevel Highest
$set = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -ExecutionTimeLimit ([TimeSpan]::Zero) -RestartCount 999 -RestartInterval (New-TimeSpan -Minutes 1)
Register-ScheduledTask -TaskName 'LANDeploy' -Action $action -Trigger $trigger -Principal $principal -Settings $set -Force | Out-Null
Start-ScheduledTask -TaskName 'LANDeploy'
Write-Host "Done. This PC ($env:COMPUTERNAME) will appear in the LANDeploy console within a few seconds." -ForegroundColor Green
"""


def setup_cmd(base, token):
    lines = [
        "@echo off",
        "title LANDeploy agent setup",
        "net session >nul 2>&1 || (echo Right-click this file and choose \"Run as administrator\". & pause & exit /b 1)",
        f"powershell -NoProfile -ExecutionPolicy Bypass -Command \"irm '{base}/setup.ps1?t={token}' | iex\"",
        "pause",
    ]
    return "\r\n".join(lines) + "\r\n"


def setup_sh(base, token):
    return f"""#!/bin/sh
# LANDeploy agent setup for Linux - generated by {base}
set -e
[ "$(id -u)" = 0 ] || {{ echo "Run with sudo"; exit 1; }}
case "$(uname -m)" in
  x86_64|amd64) BIN={AGENTS['linux-x64']} ;;
  aarch64|arm64) BIN={AGENTS['linux-arm64']} ;;
  *) echo "Unsupported CPU: $(uname -m)"; exit 1 ;;
esac
command -v zenity >/dev/null || (apt-get install -y zenity || dnf install -y zenity || pacman -S --noconfirm zenity || true) >/dev/null 2>&1
mkdir -p /opt/landeploy-agent
systemctl stop landeploy-agent 2>/dev/null || true
if command -v wget >/dev/null; then wget -qO /opt/landeploy-agent/landeploy-agent "{base}/agent/bin/$BIN"
else curl -fsSL -o /opt/landeploy-agent/landeploy-agent "{base}/agent/bin/$BIN"; fi || {{
  echo "The server has no Linux agent program: use a LANDeploy release build."; exit 1; }}
chmod 755 /opt/landeploy-agent/landeploy-agent
rm -f /opt/landeploy/landeploy_agent.py 2>/dev/null || true   # old Python-based agent
cat > /etc/systemd/system/landeploy-agent.service <<EOF
[Unit]
Description=LANDeploy agent
After=network-online.target
Wants=network-online.target

[Service]
ExecStart=/opt/landeploy-agent/landeploy-agent --server {base} --token {token}
Restart=always
RestartSec=10

[Install]
WantedBy=multi-user.target
EOF
systemctl daemon-reload
systemctl enable --now landeploy-agent
systemctl restart landeploy-agent
echo "Done. $(hostname) will appear in the LANDeploy console within a few seconds."
"""
